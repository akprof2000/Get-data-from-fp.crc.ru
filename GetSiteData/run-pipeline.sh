#!/usr/bin/env bash
# ============================================================
#  Конвейер сбора данных с fp.crc.ru - все этапы подряд.
#  Настройки - в appsettings.json рядом с этим файлом.
#  Пятый, необязательный этап (выгрузка в ClickHouse) НЕ входит
#  в цепочку и запускается отдельно:
#     python3 json_to_clickhouse.py --input-dir works/OutputNormalized
# ============================================================
set -u
cd "$(dirname "$0")"

fail() {
    echo
    echo "============================================"
    echo "  ОШИБКА на этапе: $1 (код $2)"
    echo "  Конвейер остановлен, следующие этапы не запускались."
    echo "============================================"
    echo
    exit "$2"
}

# Код возврата сохраняем в rc сразу после запуска: любая следующая команда
# (echo, [ ... ]) перезатирает $?. Конструкции вида «cmd || fail "$?"» здесь
# не используем - в них код этапа терялся и наружу уходил 0.
run_step() {
    local name="$1"
    shift
    echo
    echo "[$name]"
    "$@"
    local rc=$?
    if [ "$rc" -ne 0 ]; then
        fail "$name" "$rc"
    fi
}

echo
echo "============================================"
echo "  Конвейер fp.crc.ru: сбор -> JSON"
echo "============================================"

# Этапы 1-2 ведёт pipeline-years.sh: один год — обычная пара "сбор -> разбор",
# несколько лет — погодовой цикл со сносом HTML каждого года после разбора и
# отметками works/.years-done (перезапуск продолжает с недособранного года).
run_step "1-2/6 Сбор страниц и разбор в тексты" ./pipeline-years.sh "$(pwd)"
run_step "3/6 Классификация"                   ./bin/MLTextToData process
run_step "4/6 Извлечение данных в JSON"        ./bin/ParseTextHeader

# Нормализация адресов по офлайн-базе ГАР. Базы нет - приложение само пытается
# её собрать (по URL или из локальной выгрузки GarSource); собрать неоткуда -
# этап пропускается без ошибки, конвейер продолжается.
run_step "5/6 Обновление базы ГАР+OSM"     ./bin/NormalizeAddress update
run_step "6/6 Нормализация адресов по ГАР" ./bin/NormalizeAddress normalize

echo
echo "============================================"
echo "  Готово. Результат:"
echo "    works/OutputJson/        - все записи (неполные помечены полем missingFields)"
echo "    works/OutputErrors/      - неполные записи"
echo "    works/OutputNormalized/  - записи с нормализованным адресом (если есть база ГАР)"
echo
echo "  Выгрузить в ClickHouse (необязательно):"
echo "    python3 json_to_clickhouse.py --input-dir works/OutputJson"
echo "============================================"
echo
